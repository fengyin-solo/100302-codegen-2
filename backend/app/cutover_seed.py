def _order(
    oid: int,
    no: str,
    site: str,
    element: str,
    start: str,
    end: str,
    *,
    change_type: str,
    content: str,
    applicant: str,
    submitted: str,
    rollback: str,
    status: str,
    source_no: str | None = None,
    seats: list[dict[str, Any]] | None = None,
    steps: list[dict[str, Any]] | None = None,
    frozen: dict[str, Any] | None = None,
    logs: list[dict[str, str]] | None = None,
    conclusion: str = "",
    finished_at: str = "",
) -> dict[str, Any]:
    return {
        "id": oid,
        "status": status,
        "pending": status not in ("已回退", "已完结"),
        "abnormal": status in ("已回退", "会签未通过"),
        "工单号": no,
        "所属站点": site,
        "网元编号": element,
        "变更类型": change_type,
        "窗口开始": start,
        "窗口结束": end,
        "变更内容": content,
        "提报人": applicant,
        "提报时间": submitted,
        "回退方案": rollback,
        "源工单号": source_no,
        "会签席位": seats if seats is not None else [{"席位": s, "结论": None, "意见": "", "签署时间": None, "签署人": None} for s in SEATS],
        "会签留档": frozen,
        "执行环节": steps if steps is not None else [{"环节": s, "确认人": None, "确认时间": None, "执行记录": ""} for s in STEPS],
        "完结结论": conclusion,
        "完结时间": finished_at,
        "流转日志": logs or [{"时间": submitted, "环节": "立项", "说明": f"{applicant} 提报割接工单"}],
    }


